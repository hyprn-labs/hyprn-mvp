"""Generate the attested schema from the reviewed launch roots; no candidate code."""

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent / 'src'))
from hyprn_mvp_app import contracts

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'contracts/schemas/execution.schema.json'


def references(value):
    if isinstance(value, dict):
        for key, child in value.items():
            if key == '$ref':
                if not isinstance(child, str) or not child.startswith('#/$defs/'):
                    raise ValueError('Only local definition references are supported')
                yield child.removeprefix('#/$defs/')
            else:
                yield from references(child)
    elif isinstance(value, list):
        for child in value:
            yield from references(child)


def generated_schema():
    authored = contracts.authored_schema()
    definitions = authored['$defs']
    reached, pending = set(), list(contracts.EXECUTION_ROOTS)
    while pending:
        name = pending.pop()
        if name not in reached:
            reached.add(name)
            pending.extend(references(definitions[name]))
    return {
        '$schema': authored['$schema'],
        '$id': 'https://hyprn-mvp.local/contracts/execution.schema.json',
        '$defs': {name: body for name, body in definitions.items() if name in reached},
        '$comment': (
            'Generated by application/generate_execution_schema.py '
            'from reviewed launch-path roots. '
            'Do not edit by hand.'
        ),
    }


def generated_bytes():
    return (json.dumps(generated_schema(), indent=2, ensure_ascii=False) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = generated_bytes()
    if args.check:
        if OUTPUT.read_bytes() != raw:
            parser.exit(1, 'Execution schema differs from the reviewed root closure.\n')
    else:
        OUTPUT.write_bytes(raw)


if __name__ == '__main__':
    main()
