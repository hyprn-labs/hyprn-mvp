"""Capture the native program fixture through the reviewed private static producer.

Explicit utility, never collected as a test module (test_native_program imports ``capture``).
No candidate is imported or executed.

    HYPRN_MVP_MODEL_TEST_ROOT=<scoped service root> HYPRN_MVP_MODEL_TEST_CONTAINER=<test container> \\
        python3 integration/tests/capture_native_programs.py

The service under test must run the reviewed producer image pinned in deployment/pins.json
(``modeling_producer``). Each case below is an authored model-format-1 revision (the format of
these fixture cases; the producer writes new drafts in format 2, so a case enters the producer
as a portable model package through the authenticated import). The producer validates the
package and its digests, then prepares the committed revision twice (the second time after an
edit of the imported live draft, which must keep the executable digest); every declared file is
fetched by its authenticated file id and checked against its size and SHA-256. The native
generator produces every generated byte. The fixture is written anew from these cases: no
earlier case or blob is carried over.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT), str(ROOT / 'application/src')]
from contracts.tests.test_modeling_contract import candidate, source, uid  # noqa: E402
from deployment.tests import model_client  # noqa: E402
from deployment.tests.model_client import ModelClient  # noqa: E402
from hyprn_mvp_app.store import canonical, digest  # noqa: E402

IMAGE = json.loads((ROOT / 'deployment/pins.json').read_text())['modeling_producer']['image']
FIXTURE = ROOT / 'integration/tests/fixtures/native-programs.json.gz'
# Package origin exactly as the producer's own export writes it.
SOURCE_SERVICE = 'whatsopt-597f5abf/modeling-1'
PACKAGE_NOTICES = ['WhatsOpt and in-process adapter: AGPL-3.0-only; source offer required for distribution. '
                   'Authored source retains author license.']

LINEAR = b"outputs['u'] = 2 * inputs['x'] + inputs['z']\r\n# caf\xc3\xa9\r\n"
CHAIN_PORTS = ([('x', 'input', ''), ('z', 'input', ''), ('u', 'output', '')], [('u', 'input', ''), ('y', 'output', '')])
# Two-component chains: the same linear component and one downstream source per case.
CHAINS = {
    'chain': (LINEAR, b"outputs['y'] = inputs['u'] ** 2\n"),
    'chain3': (LINEAR.replace(b'2 *', b'3 *'), b"outputs['y'] = inputs['u'] ** 2\n"),
    'unwritten': (LINEAR, b'pass\n'),
    'nan': (LINEAR, b"outputs['y'] = float('nan')\n"),
    'inf': (LINEAR, b"outputs['y'] = float('inf')\n"),
    'throw': (LINEAR, b"outputs['y'] = 12\nraise RuntimeError('downstream failed')\n"),
    'retained_throw': (LINEAR, b"outputs['y']=12\nraise RuntimeError('retained failure')\n"),
    'inplace': (LINEAR, b"outputs['y'][0] = 12\n"),
    'canary': (LINEAR, b"open('/tmp/HYPRN_MVP_CANDIDATE_MUST_NOT_IMPORT', 'w').write('unsafe')\n"),
}


def chain(upstream, downstream):
    return dict(definitions=[('linear', CHAIN_PORTS[0], upstream), ('square', CHAIN_PORTS[1], downstream)],
                instances=['linear', 'square'], connections=[(0, 'u', 1, 'u')])


# Each case: definitions (name, ports as (symbol, direction, units), source bytes), instances in
# storage order (by definition name), connections (source instance, symbol, target instance,
# symbol) and the explicit input values (value, units) in candidate() order.
SPECS = {
    **{kind: dict(chain(*sources), values=[(2, ''), (3, '')]) for kind, sources in CHAINS.items()},
    'unrelated': dict(definitions=[('response', [('drive', 'input', ''), ('gain', 'input', ''), ('response', 'output', '')],
                                    b"outputs['response'] = inputs['gain'] / (1 + inputs['drive'] ** 2)\n")],
                      instances=['response'], connections=[], values=[(2, ''), (15, '')]),
    'units': dict(definitions=[('distance', [('entered', 'input', 'km'), ('travel', 'output', 'km')],
                                b"outputs['travel'] = inputs['entered']\n")],
                  instances=['distance'], connections=[], values=[(2000, 'm')]),
    'affine': dict(definitions=[('temperature', [('entered', 'input', 'K'), ('travel', 'output', 'K')],
                                 b"outputs['travel'] = inputs['entered']\n")],
                   instances=['temperature'], connections=[], values=[(20, 'K')]),
    # Repeated definition, leading underscore, disconnected identical symbols, fan-out to two
    # distinct inputs and connected native unit conversion.
    'mapping': dict(definitions=[('scale', [('_x', 'input', 'm'), ('y', 'output', 'm')], b"outputs['y'] = inputs['_x'] * 2\n"),
                                 ('sum', [('left', 'input', 'km'), ('right', 'input', 'km'), ('y', 'output', 'km')],
                                  b"outputs['y'] = inputs['left'] + inputs['right']\n")],
                    instances=['sum', 'scale', 'scale'], connections=[(2, 'y', 0, 'left'), (2, 'y', 0, 'right')],
                    values=[(1000, 'm'), (-2, 'm')]),
}
CASES = tuple(SPECS)
# Cases whose targets are keyed by instance id and whose capture record is kept; the others are
# keyed by instance name and use the frozen scientific configuration wording.
CAPTURED = ('affine', 'mapping')


def model_revision(kind):
    """The authored model-format-1 revision of one case, with fresh identifiers."""
    spec = SPECS[kind]
    definitions, by_name, sources = [], {}, []
    for name, ports, body in spec['definitions']:
        version = uid()
        definition = dict(definition_id=uid(), definition_version_id=version, kind='explicit_component', name=name,
                          ports=[dict(direction=d, name=s, code_symbol=s, value_type='real_scalar', units=u,
                                      port_id=uid(), definition_version_id=version) for s, d, u in ports],
                          source_refs=[hashlib.sha256(body).hexdigest()], residual_port_ids=[], child_instances=[],
                          boundary_mappings=[], annotations=[])
        definitions.append(definition)
        by_name[name] = definition
        if all(s['sha256'] != definition['source_refs'][0] for s in sources):
            sources.append(source(body))
    instances = [dict(instance_id=uid(), definition_version_id=by_name[name]['definition_version_id'], name=name)
                 for name in spec['instances']]

    def ref(index, symbol):
        definition = by_name[spec['instances'][index]]
        port = next(p for p in definition['ports'] if p['code_symbol'] == symbol)
        return dict(instance_id=instances[index]['instance_id'], port_id=port['port_id'])
    revision = dict(schema_version='1', model_id=uid(), root_instance_id=uid(), definitions=definitions,
                    instances=instances, ports=[p for d in definitions for p in d['ports']],
                    connections=[dict(connection_id=uid(), source_ref=ref(a, s), target_ref=ref(b, t))
                                 for a, s, b, t in spec['connections']],
                    boundary_mappings=[], annotations=[], required_capabilities=['flat_explicit_scalar'],
                    model_revision_id=uid(), parent_model_revision_id=None, originating_draft_revision=uid(),
                    source_files=sources)
    revision['digest'] = digest(revision)
    return revision


def package_files(revisions):
    """Portable package file records exactly as the producer lists them."""
    files = {}

    def add(path, raw, media, role):
        file_id = hashlib.sha256(('model-package-v1:' + path).encode()).hexdigest()[:32]
        file_id = '-'.join((file_id[:8], file_id[8:12], file_id[12:16], file_id[16:20], file_id[20:]))
        files[path] = dict(file_id=file_id, path=path, size=len(raw), sha256=hashlib.sha256(raw).hexdigest(),
                           media_type=media, role=role)
    for revision in revisions:
        add('revisions/' + revision['model_revision_id'] + '.json', canonical(revision), 'application/json', 'model')
        for item in revision['source_files']:
            add('sources/' + item['sha256'] + '.py', base64.b64decode(item['bytes']), 'text/x-python', 'source')
    return [files[path] for path in sorted(files)]


def package(revision):
    value = dict(schema_version='1', source_service=SOURCE_SERVICE, model_id=revision['model_id'],
                 model_revision_id=revision['model_revision_id'], revisions=[revision], files=package_files([revision]),
                 required_capabilities=revision['required_capabilities'], license_notices=PACKAGE_NOTICES)
    value['digest'] = digest(value)
    return value


def configuration(kind, model, study):
    config = candidate(model, study)
    config.update(configuration_id=uid(), configuration_revision_id=uid(), parent_revision_id=None)
    if kind not in CAPTURED:
        config.update(name='Frozen test configuration',
                      context_snapshot=dict(description='Retained context', boundary='', notes=[]))
        for value in config['inputs']:
            value['provenance']['statement'] = 'Explicit scientific fixture'
    if len(config['inputs']) != len(SPECS[kind]['values']):
        raise ValueError('Unexpected free inputs for ' + kind)
    for value, (number, units) in zip(config['inputs'], SPECS[kind]['values']):
        value.update(value=number, units=units)
    config['digest'] = digest(config)
    return config


def capture(kind, blobs):
    client = ModelClient()
    model = model_revision(kind)
    draft = client.call('POST', '/imports', dict(command_id=uid(), expected_revision=None, study_id=client.study,
                                                 package=package(model), preserve_public_ids=True), status=201)['data']
    path = '/models/' + model['model_id']
    assert client.call('GET', path + '/revisions/' + model['model_revision_id'])['data'] == model
    config = configuration(kind, model, client.study)
    body = dict(command_id=uid(), model_revision_id=model['model_revision_id'],
                configuration_snapshot=config, configuration_digest=config['digest'])
    prepared = client.call('POST', path + '/prepare-execution', body)['data']
    assert prepared['schema_version'] == '3'
    assert prepared['result_protocol_version'] == '2'
    # Preparing a committed revision after a current draft edit must be invariant.
    client.edit(draft, [dict(kind='rename_instance', instance_id=model['instances'][0]['instance_id'],
                             name='Edited current draft after commit')])
    second = client.call('POST', path + '/prepare-execution', {**body, 'command_id': uid()})['data']
    assert second['executable_content_digest'] == prepared['executable_content_digest']
    assert client.call('GET', path + '/revisions/' + model['model_revision_id'])['data'] == model
    for descriptor in prepared['files']:
        sha = descriptor['sha256']
        if sha not in blobs:
            blobs[sha] = client.call('GET', '/preparations/' + prepared['preparation_id'] +
                                     '/files/' + descriptor['file_id'])['data']['bytes']
        raw = base64.b64decode(blobs[sha], validate=True)
        assert len(raw) == descriptor['size'] and hashlib.sha256(raw).hexdigest() == sha
    definitions = {d['definition_version_id']: d for d in model['definitions']}
    key = (lambda i: i['instance_id']) if kind in CAPTURED else (lambda i: i['name'])
    targets = {key(i): {p['code_symbol']: dict(instance_id=i['instance_id'], port_id=p['port_id'])
                        for p in definitions[i['definition_version_id']]['ports']} for i in model['instances']}
    case = dict(prepared=prepared, frozen=dict(configuration=config, model_snapshot=model, study_revision=uid()),
                targets=targets)
    if kind in CAPTURED:
        case['capture'] = dict(draft_edit_invariance=True, repeated_preparation_id=second['preparation_id'],
                               producer_image=IMAGE)
    return case


def main():
    observed = json.loads(subprocess.check_output(['docker', 'inspect', model_client._container()]))[0]
    if observed['Image'] != IMAGE:
        raise SystemExit('The service under test does not run the reviewed producer image')
    blobs, cases = {}, {}
    for kind in CASES:
        cases[kind] = capture(kind, blobs)
        print('captured', kind, flush=True)
    used = {f['sha256'] for case in cases.values() for f in case['prepared']['files']}
    data = dict(producer_image=IMAGE, cases=cases, blobs={sha: blobs[sha] for sha in sorted(used)})
    FIXTURE.write_bytes(gzip.compress(json.dumps(data, separators=(',', ':')).encode(), mtime=0))
    print('written', len(cases), 'cases', len(data['blobs']), 'blobs', flush=True)


if __name__ == '__main__':
    main()
